from typing import Dict, Optional, List
from pydantic import (
    BaseModel,
    ConfigDict,
    Field, model_validator,
)
from docy import const

class VariableSchema(BaseModel):
    name: Optional[str] = Field(None, description="Variable name")
    value: Optional[str] = Field(None, description="Variable value")
    required: bool = Field(False, description="Whether required")

class CustomComponentRequest(BaseModel):

    agent_code: str = Field(..., description="agent id")
    code: str = Field(..., description="Source code string")
    is_extract: bool = Field(False, description="Whether data is exported to the result")
    variables: List[VariableSchema] = Field([], description="Variable list")


class CreateCustomComponent(BaseModel):
    """Create a custom node"""
    node_id: str
    agent_id: str
    code: str = Field(..., description="Source code string")
    name: str = Field(..., description="Component name")
    display_name: Optional[str] = Field(..., description="Component display name")
    description: Optional[str] = Field(..., description="Component description")
    extra: Dict = Field(..., description="Data parsed from the source code")
    is_extract: bool = Field(False, description="Whether data is exported to the result")
    variables: List[VariableSchema] = Field([], description="Variable list")
    market_id: Optional[str] = Field(None, description="Marketplace id")

class ResponseCustomComponent(CreateCustomComponent):
    """Response data"""
    model_config = ConfigDict(from_attributes=True)

    id: Optional[str] = Field(None, description="Node id")
    name: Optional[str] = Field(None, description="Component name")
    display_name: Optional[str] = Field(None, description="Component display name")
    description: Optional[str] = Field(None, description="Component description")
    variables: Optional[List[VariableSchema]] = Field(None, description="Variable list")

    @model_validator(mode="before")
    def validate_variables(cls, obj):
        if hasattr(obj, "variables"):
            extra = getattr(obj, "extra", {})
            if hasattr(obj, "auth_type") and obj.auth_type == const.AT_AI_API_KEY:
                extra["variables"] = obj.variables
            else:
                variables = obj.variables
                if variables:
                    for variable in variables:
                        if variable.get("value"):
                            variable["value"] = "*" * 10
                extra["variables"] = obj.variables
        return obj



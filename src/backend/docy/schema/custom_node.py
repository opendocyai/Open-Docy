class Input(BaseModel):
    name: Optional[str] = Field("InputFile-input")
    display_name: Optional[str] = Field("InputFile-input")
    socket: Optional[str] = Field("any")
    multipleConnections: Optional[bool] = Field(False, description="Whether multiple connections are supported")


class Output(BaseModel):

    name: Optional[str] = Field("InputFile-output")
    display_name: Optional[str] = Field("InputFile-output")
    socket: Optional[str] = Field("any")
    method: str = Field(..., description="return function")

class Variable(BaseModel):
    name: Optional[str] = Field(None, description="variable name")
    required: Optional[bool] = Field(False, description="if required")

import argparse
import asyncio
from pathlib import Path

from alembic import command, util
from alembic.config import Config
from loguru import logger
from sqlalchemy.ext.asyncio import AsyncEngine
from sqlmodel import SQLModel, text
from sqlmodel.ext.asyncio.session import AsyncSession

from docy.bases.dbs import Base
from docy.database.db_sqllite import SQLiteDatabase
from docy.database import get_async_db_connector, get_engine


class DatabaseService:
    name = "database_service"

    def __init__(self, database_url: str):
        self.database_url: str = database_url
        self.engine: AsyncEngine = self._create_engine()

        docy_dir = Path(__file__).resolve().parent.parent
        self.script_location = docy_dir / "alembic"
        self.alembic_cfg_path = docy_dir / "alembic.ini"

    def _create_engine(self) -> AsyncEngine:
        return get_engine(is_async=True)

    # Migration helpers

    async def run_migrations(self, *, fix: bool = False, quiet: bool = False) -> None:
        """Run database migrations at startup."""
        should_init = False
        async with get_async_db_connector() as session:
            try:
                await session.exec(text("SELECT 1 FROM alembic_version"))
            except Exception:
                logger.info("Alembic not initialized; running the first migration")
                should_init = True

        versions_dir = self.script_location / "versions"
        has_revisions = versions_dir.is_dir() and any(versions_dir.glob("*.py"))
        if not has_revisions:
            if should_init:
                # No migration scripts shipped: create tables directly from the models.
                await self.create_db_and_tables()
            else:
                logger.info("No migration scripts; skipping the check")
            return

        await asyncio.to_thread(self._run_migrations, should_init, fix, quiet)

    def _autogenerate(self, alembic_cfg: Config) -> None:
        """Generate a migration file and log its path."""
        logger.info("Model changes detected; autogenerating migration file...")
        versions_dir = Path(alembic_cfg.get_main_option("script_location")) / "versions"
        before = set(str(p) for p in versions_dir.glob("*.py")) if versions_dir.exists() else set()
        command.revision(alembic_cfg, autogenerate=True, message="auto migration")
        after = set(str(p) for p in versions_dir.glob("*.py")) if versions_dir.exists() else set()
        new_files = after - before
        for f in new_files:
            logger.info(f"Migration file generated: {f}")

    def _run_migrations(self, should_init: bool, fix: bool, quiet: bool = False) -> None:
        alembic_cfg = Config(str(self.alembic_cfg_path))
        alembic_cfg.set_main_option("script_location", str(self.script_location))
        alembic_cfg.set_main_option("sqlalchemy.url", self.database_url.replace("%", "%%"))
        # With quiet=True, alembic's stdout messages (e.g. "No new upgrade operations
        # detected.") are suppressed; failures still raise. messaging_opts is a
        # memoized_property and must be set before any command call.
        if quiet:
            alembic_cfg.cmd_opts = argparse.Namespace(quiet=True)

        from alembic.script import ScriptDirectory
        script = ScriptDirectory.from_config(alembic_cfg)
        has_revisions = script.get_current_head() is not None

        if should_init:
            try:
                command.ensure_version(alembic_cfg)
                if has_revisions:
                    command.upgrade(alembic_cfg, "head")
                    logger.info("Alembic initialized; upgraded to head")
                else:
                    logger.info("Alembic initialized (no migration scripts)")
            except Exception as exc:
                logger.exception("Alembic initialization failed")
                raise RuntimeError("Alembic initialization failed") from exc
            return

        if not has_revisions:
            logger.info("No migration scripts; skipping the check")
            return

        try:
            command.check(alembic_cfg)
            logger.info("Database is up to date; no migration needed")
        except util.exc.CommandError:
            # Database not at the latest revision (a previous migration may have failed;
            # the user fixed the migration file and is retrying)
            logger.warning("Database is not at the latest revision; running upgrade...")
            command.upgrade(alembic_cfg, "head")
            logger.info("upgrade complete")
            # Re-check for model changes after the upgrade
            try:
                command.check(alembic_cfg)
            except util.exc.AutogenerateDiffsDetected:
                if not fix:
                    self._autogenerate(alembic_cfg)
                    command.upgrade(alembic_cfg, "head")
        except util.exc.AutogenerateDiffsDetected:
            # Database is current, but models differ from the database schema
            if not fix:
                self._autogenerate(alembic_cfg)
                command.upgrade(alembic_cfg, "head")

        if fix:
            command.upgrade(alembic_cfg, "head")

        try:
            command.check(alembic_cfg)
        except util.exc.AutogenerateDiffsDetected as exc:
            msg = f"Model and database are out of sync: {exc}"
            logger.error(msg)
            raise RuntimeError(msg) from exc

    # Fallback path

    @staticmethod
    def _import_all_models() -> None:
        """Import every model module so all tables are registered in the metadata."""
        import importlib

        models_dir = Path(__file__).resolve().parent.parent / "models"
        for path in sorted(models_dir.glob("tb_*.py")):
            module_name = f"docy.models.{path.stem}"
            try:
                importlib.import_module(module_name)
            except Exception as exc:
                logger.warning(f"Failed to import model module {module_name}: {exc}")

    async def create_db_and_tables(self) -> None:
        """Fallback when no alembic migration scripts exist: create tables directly from models."""
        self._import_all_models()

        def _create_all(sync_conn) -> None:
            Base.metadata.create_all(sync_conn)
            SQLModel.metadata.create_all(sync_conn)

        async with self.engine.begin() as conn:
            await conn.run_sync(_create_all)
        logger.info("Database tables created (create_all)")

    async def close(self) -> None:
        await self.engine.dispose()
        logger.info("Database engine closed")
